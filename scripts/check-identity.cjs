// T08 — profiles, hidden profile, incognito: the home shows a mark and no name; switching isolates drafts and search;
// unhiding is by full password in search; acceptance adds the contact and names the identity once; the composer names it. Browser simulation only.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE);
(async()=>{const b=await chromium.launch({headless:true,executablePath:process.env.BROWSER_PATH});const p=await b.newPage({viewport:{width:390,height:844}});const errors=[];p.on('pageerror',e=>errors.push(e.message));
const checks=[],ck=(v,t)=>{if(!v)throw Error('FAIL: '+t);checks.push(t)};const txt=s=>p.locator(s).first().innerText();
await p.goto('file://'+process.cwd()+'/v21.html?mobile=1&version=2.1.2.1');
ck(await p.locator('[data-action=profiles]').count()===1,'Home has one profile mark');
ck(!(await txt('.head')).includes('Austin'),'No profile name in the home header');
ck(await p.evaluate(()=>getComputedStyle(document.querySelector('[data-action=profiles]')).backgroundColor!=='rgba(0, 0, 0, 0)'),'The self mark is filled; contacts are not');
await p.fill('#search','ma');await p.click('[data-open=maya]');await p.fill('#reply','See you Saturday');await p.click('[data-action=home]');
ck(await p.inputValue('#search')==='ma','Austin search kept before switching');
await p.click('[data-action=profiles]');
ck(await p.locator('#profiles[open]').count()===1,'Profile sheet opens');
ck(await p.locator('[data-profile]').count()===2,'Two visible profiles; the hidden one is not listed');
ck((await txt('[data-profile=austin]')).includes('Active'),'Current profile marked Active');
ck(!(await p.locator('#profiles').innerText()).includes('Personal'),'Hidden profile never named in the sheet');
await p.click('[data-profile=work]');
ck((await txt('[data-action=profiles]'))==='W','Mark changes to W after switching');
ck(await p.locator('[data-open=priya]').count()>=1&&await p.locator('[data-open=maya]').count()===0,'Work has its own connections; Maya absent');
ck(await p.inputValue('#search')==='','Work search is empty, not Austin\'s');
ck(!(await txt('.feedback')).includes('Maya'),'Switch feedback names no contact of the other profile');
await p.click('[data-action=profiles]');await p.click('[data-profile=austin]');
ck(await p.inputValue('#search')==='ma','Austin search restored after switching back');
ck((await txt('[data-open=maya] .preview')).includes('Draft'),'Austin draft marker restored');
await p.fill('#search','lighthouse-187');
ck(await p.locator('[data-action=unhide]').count()===0&&(await txt('.empty')).includes('No connections found'),'Partial password shows only the ordinary empty state');
await p.fill('#search','lighthouse-1874');
ck((await txt('[data-action=unhide]'))==='Unhide Personal profile','Full password offers Unhide');
await p.click('[data-action=unhide]');
ck((await txt('[data-action=profiles]'))==='P'&&await p.locator('[data-open=jo]').count()>=1,'Unhiding switches to the profile');
await p.click('[data-action=profiles]');
ck(await p.locator('[data-profile]').count()===3,'Unhidden profile now listed');
await p.click('[data-profile=austin]');
await p.click('[data-action=invite]');await p.check('#incognito');
ck((await txt('#identity')).includes('River Finch'),'Generated name shown before the invitation exists');
await p.click('[data-action=create-invite]');
ck(await p.locator('#incognito').isDisabled()&&(await txt('#identity')).startsWith('Set when the invitation was created'),'Choice frozen while pending, with the reason');
await p.click('[data-action=accept-invite]');await p.waitForTimeout(50);
ck(await p.locator('#invite[open]').count()===0,'Dialog closes on acceptance');
ck(await p.evaluate(()=>document.activeElement?.dataset.open==='sam'),'New contact row focused');
ck(await p.evaluate(()=>document.querySelector('.rows [data-open=sam]').getBoundingClientRect().top<400),'New contact row on screen');
ck((await txt('.feedback')).includes('as River Finch'),'Feedback names the identity once');
ck(!(await txt('[data-open=sam]')).includes('River Finch'),'The row carries no identity');
await p.click('[data-open=sam]');
ck((await txt('.dock .note')).includes('as River Finch')&&(await p.getAttribute('#reply','placeholder')).includes('as River Finch'),'Composer names the incognito identity');
ck((await txt('.boundary')).includes('knows you as River Finch'),'Unverified note states what Sam sees');
await p.click('[data-action=home]');
ck(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No horizontal overflow');
ck(errors.length===0,'No page errors: '+errors.join('; '));
await b.close();console.log('PASS '+checks.length+' T08 identity checks');})().catch(e=>{console.error(e.message);process.exit(1)});
